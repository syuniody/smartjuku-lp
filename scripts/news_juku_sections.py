def ps(items: list[str]) -> str:
    return "\n".join(f"        <p>{t}</p>" for t in items)


def apply(slug: str, cfg: dict) -> str:
    section = cfg.get("dir", "news")     # 既定は /news/。guide などに置いた記事は dir で指定
    path = ROOT / section / f"{slug}.html"
    if not path.exists():
        return f"{slug}: {section}/{slug}.html がありません（import_note.py を先に実行）"
    s = path.read_text(encoding="utf-8")

    s = s.replace(
        '<meta name="description" content="★この記事の要点を、塾長にとっての意味を含めて2文で。全角120字前後。">',
        f'<meta name="description" content="{cfg["desc"]}">')
    s = s.replace(
        '<meta property="og:description" content="★この記事の要点を、塾長にとっての意味を含めて2文で。">',
        f'<meta property="og:description" content="{cfg["ogd"]}">')
    s = s.replace(
        '<meta name="sj:ogp-lead" content="★共有時に出す一行（数値があれば入れる）">',
        f'<meta name="sj:ogp-lead" content="{cfg["lead"]}">')
    s = s.replace('"description": "★この記事の要点を2文で。",', f'"description": "{cfg["ogd"]}",')
    s = s.replace(
        '<p class="article-lede">★塾長向けのリード文。この制度変更が塾の何に効くのかを2〜3文で。</p>',
        f'<p class="article-lede">{cfg["lede"]}</p>')

    old = """        <h2>この記事は塾にどう効くか</h2>
        <div class="answer">
          <p>★結論を1〜2文で。</p>
        </div>

        <h3>保護者への説明材料になるか</h3>
        <p>★面談や保護者会でどう使えるか。</p>

        <h3>指導・カリキュラムへの影響</h3>
        <p>★教える中身や進め方が変わるか。変わらないなら、そう書く。</p>

        <h3>発信のネタとして使えるか</h3>
        <p>★塾のブログやLINEで扱うときの切り口。</p>"""
    new = f"""        <h2>この記事は塾にどう効くか</h2>
        <div class="answer">
{ps(cfg["answer"])}
        </div>

        <h3>保護者への説明材料になるか</h3>
{ps(cfg["hogosha"])}

        <h3>{cfg.get("impact_heading", "指導・カリキュラムへの影響")}</h3>
{ps(cfg["shidou"])}

        <h3>発信のネタとして使えるか</h3>
{ps(cfg["hasshin"])}"""
    if old not in s:
        return f"{slug}: 追記の差し込み位置が見つかりません（すでに反映済み？）"
    s = s.replace(old, new)

    path.write_text(s, encoding="utf-8")
    return f"{slug}: 追記しました（★の残り {s.count('★')} 件）"


def main() -> int:
    for slug, cfg in SECTIONS.items():
        print(" ", apply(slug, cfg))
    return 0


if __name__ == "__main__":
    sys.exit(main())
